// Package contracts derives shared UI data shapes from the server's JSON DTOs.
package contracts

//go:generate go run ../../scripts/generate-contracts.go ../../packages/ui/models.generated.ts

import (
	"fmt"
	"netgo/internal/diagnostics"
	"netgo/internal/model"
	"netgo/internal/remote"
	"netgo/internal/store"
	"reflect"
	"strings"
	"time"
)

func TypeScript() string {
	var out strings.Builder
	out.WriteString("// Generated by go generate ./internal/contracts. Do not edit.\n")
	for _, value := range []any{
		model.CleanupRetry{}, model.Resource{}, model.User{}, model.Device{}, model.Lease{}, model.DeleteResult{},
		model.Host{}, model.RemoteGrant{}, model.RemoteSession{}, remote.HostSummary{}, remote.GrantSummary{}, remote.Inventory{}, remote.InventoryPage{},
		store.UserChoice{}, store.UserChoices{}, store.RemoteHistory{}, diagnostics.Check{}, diagnostics.Alert{}, diagnostics.HostResources{}, diagnostics.RuntimeReport{},
	} {
		t := reflect.TypeOf(value)
		fmt.Fprintf(&out, "export type %s = {\n", t.Name())
		fields(&out, t)
		out.WriteString("}\n")
	}
	return out.String()
}

func fields(out *strings.Builder, t reflect.Type) {
	for i := 0; i < t.NumField(); i++ {
		field := t.Field(i)
		if field.Anonymous {
			fields(out, field.Type)
			continue
		}
		parts := strings.Split(field.Tag.Get("json"), ",")
		if parts[0] == "-" || parts[0] == "" {
			continue
		}
		optional := ""
		for _, option := range parts[1:] {
			if option == "omitempty" {
				optional = "?"
			}
		}
		fmt.Fprintf(out, "  %s%s: %s\n", parts[0], optional, typeName(field.Type))
	}
}

func typeName(t reflect.Type) string {
	if t == reflect.TypeOf(time.Time{}) {
		return "string"
	}
	switch t.Kind() {
	case reflect.String:
		return "string"
	case reflect.Bool:
		return "boolean"
	case reflect.Int, reflect.Int8, reflect.Int16, reflect.Int32, reflect.Int64,
		reflect.Uint, reflect.Uint8, reflect.Uint16, reflect.Uint32, reflect.Uint64, reflect.Float32, reflect.Float64:
		return "number"
	case reflect.Slice:
		return typeName(t.Elem()) + "[]"
	case reflect.Struct:
		return t.Name()
	case reflect.Map:
		if t.Key().Kind() != reflect.String {
			panic("UI maps require string keys")
		}
		return "Record<string, " + typeName(t.Elem()) + ">"
	default:
		panic("unsupported UI contract type: " + t.String())
	}
}
